// Builds assets/tokens.css (CSS custom properties) from assets/tokens.json (W3C Design Tokens format).
// Run after editing tokens.json:   npm run tokens
// The tests fail if tokens.css is out of date. No dependencies.
//
// Names: the set name is dropped, and so is a leading "color" group, so
//   light.color.bg -> --bg     light.shadow.card -> --shadow-card     core.space.4 -> --space-4
// The light set is the default; the dark set applies when the device is dark (unless the participant
// picked Light) or when they picked Dark (assets/theme.js sets <html data-theme>). The classes
// .theme-light and .theme-dark apply one palette to a single element, e.g. a preview swatch.
// A value written as "{core.space.4}" refers to another token and becomes var(--space-4).
"use strict";
const fs = require("fs");
const path = require("path");

const SRC = path.join(__dirname, "..", "assets", "tokens.json");
const OUT = path.join(__dirname, "..", "assets", "tokens.css");
const GENERIC = new Set(["serif", "sans-serif", "monospace", "cursive", "fantasy", "system-ui", "ui-serif",
  "ui-sans-serif", "ui-monospace", "ui-rounded", "math", "emoji", "fangsong", "-apple-system"]);

// Every token in a set, with the $type inherited from its groups.
function flatten(group, type, prefix, out = []) {
  for (const [key, node] of Object.entries(group)) {
    if (key.startsWith("$") || !node || typeof node !== "object") continue;
    const t = node.$type || type;
    if ("$value" in node) out.push({ path: [...prefix, key], type: t, value: node.$value, description: node.$description });
    else flatten(node, t, [...prefix, key], out);
  }
  return out;
}

const varName = p => "--" + (p[1] === "color" ? p.slice(2) : p.slice(1)).join("-");
const unit = v => typeof v === "object" && v !== null && "value" in v ? `${v.value}${v.unit}` : String(v);   // "4px" or {value:4, unit:"px"}
function color(v) {
  if (typeof v === "string") return v;
  if (v.hex) return v.alpha == null || v.alpha >= 1 ? v.hex : v.hex + Math.round(v.alpha * 255).toString(16).padStart(2, "0");
  const [r, g, b] = v.components.map(c => Math.round(c * 255));
  return `rgb(${r} ${g} ${b}${v.alpha == null || v.alpha >= 1 ? "" : ` / ${v.alpha}`})`;
}
function format(tok, names) {
  const v = tok.value;
  if (typeof v === "string" && /^\{.+\}$/.test(v)) {                // reference to another token
    const name = varName(v.slice(1, -1).split("."));
    if (!names.has(name)) throw new Error(`${tok.path.join(".")} refers to ${v}, which is not a token`);
    return `var(${name})`;
  }
  switch (tok.type) {
    case "color": return color(v);
    case "dimension": case "duration": return unit(v);
    case "fontFamily": return [].concat(v).map(f => GENERIC.has(f) || !/[\s\d]/.test(f) ? f : `"${f}"`).join(", ");
    case "fontWeight": case "number": return String(v);
    case "cubicBezier": return `cubic-bezier(${v.join(", ")})`;
    case "shadow": return [].concat(v).map(s => [s.inset ? "inset" : "", unit(s.offsetX), unit(s.offsetY), unit(s.blur),
      unit(s.spread || "0px"), color(s.color)].filter(Boolean).join(" ")).join(", ");
    default: throw new Error(`${tok.path.join(".")}: unsupported $type "${tok.type}"`);
  }
}

function build(json = JSON.parse(fs.readFileSync(SRC, "utf8"))) {
  const sets = Object.fromEntries(["core", "light", "dark"].map(s => {
    if (!json[s]) throw new Error(`tokens.json needs a "${s}" set`);
    return [s, flatten(json[s], undefined, [s])];
  }));
  const names = new Set(Object.values(sets).flat().map(t => varName(t.path)));
  const lightNames = sets.light.map(t => varName(t.path)).join(), darkNames = sets.dark.map(t => varName(t.path)).join();
  if (lightNames !== darkNames) throw new Error("the light and dark sets must define the same tokens, in the same order");

  const lines = (toks, indent, notes) => toks.map(t =>
    `${indent}${varName(t.path)}: ${format(t, names)};${notes && t.description ? ` /* ${t.description} */` : ""}`).join("\n");
  return `/* Design tokens. GENERATED from tokens.json by tools/build-tokens.js: do not edit this file.
   Change tokens.json, then run \`npm run tokens\`. */

/* Shared: type, spacing, radius, motion */
:root {
${lines(sets.core, "  ", true)}
}

/* Light (the default) */
:root, .theme-light {
  color-scheme: light;
${lines(sets.light, "  ", true)}
}

/* Dark: when the device is dark and the participant has not picked Light */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${lines(sets.dark, "    ", false)}
  }
}

/* Dark: when the participant picked Dark */
:root[data-theme="dark"], .theme-dark {
  color-scheme: dark;
${lines(sets.dark, "  ", false)}
}
`;
}

module.exports = { build, SRC, OUT };

if (require.main === module) {
  fs.writeFileSync(OUT, build());
  console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
}
